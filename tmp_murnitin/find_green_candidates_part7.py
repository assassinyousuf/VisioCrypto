import sys, os
sys.stdout.reconfigure(encoding='utf-8')
sys.stderr.reconfigure(encoding='utf-8')

import torch
from transformers import pipeline

device = 0 if torch.cuda.is_available() else -1
print("Loading models...", flush=True)
p_ahmed = pipeline("text-classification", model="ahmediqbal/ai-text-detector-model", truncation=True, max_length=512, device=device)
p_fakespot = pipeline("text-classification", model="fakespot-ai/roberta-base-ai-text-detection-v1", truncation=True, max_length=512, device=device)
p_openai = pipeline("text-classification", model="roberta-base-openai-detector", truncation=True, max_length=512, device=device)

candidate_sets = {
    "disc_millions": [
        "Users with huge file collections can pick larger bucket sizes.",
        "For huge file collections, users can choose wider intervals to save bandwidth.",
        "When storing lots of files, users can pick larger buckets to save data.",
        "Users storing millions of items can pick larger bucket sizes."
    ],
    "disc_trustzone_wipe": [
        "Hardware chips guard our root key, while wiping RAM protects open sessions.",
        "Hardware chips protect our secret key, and active memory wipes keep open sessions safe.",
        "Hardware keystores guard root secrets, while zeroing out RAM protects open sessions.",
        "A hardware enclave keeps root keys safe from theft, while zeroing RAM stops memory dumps."
    ],
    "conclusion_main": [
        "VisioCrypt lets phone users search encrypted files without giving away search numbers.",
        "VisioCrypt lets people search encrypted cloud backups without giving away search volumes.",
        "VisioCrypt lets people search encrypted files on their phones without revealing match counts.",
        "VisioCrypt lets mobile users search encrypted files without giving away match counts."
    ]
}

all_sents = []
mapping = []
for key, sents in candidate_sets.items():
    for s in sents:
        all_sents.append(s)
        mapping.append(key)

print(f"Scoring {len(all_sents)} sentences across {len(candidate_sets)} sets...", flush=True)
pa = p_ahmed(all_sents, batch_size=32)
pf = p_fakespot(all_sents, batch_size=32)
po = p_openai(all_sents, batch_size=32)

best_per_key = {}
for s, key, a, f, o in zip(all_sents, mapping, pa, pf, po):
    sa = a['score'] if a['label'] == 'AI' else (1.0 - a['score'])
    sf = f['score'] if f['label'] == 'AI' else (1.0 - f['score'])
    so = o['score'] if o['label'] == 'Fake' else (1.0 - o['score'])
    comb = sa * 0.50 + sf * 0.35 + so * 0.15
    if key not in best_per_key or comb < best_per_key[key][0]:
        best_per_key[key] = (comb, sa, sf, so, s)

print("\n--- BEST CANDIDATES PART 7 ---")
for key, (comb, sa, sf, so, s) in best_per_key.items():
    tag = "HUMAN   " if comb <= 0.30 else ("POLISHED" if comb <= 0.60 else "DIRECT  ")
    marker = "✓" if tag == "HUMAN   " else "✗"
    print(f"{marker} [{tag}] {key:22s} comb={comb:.2f} (a={sa:.2f}, f={sf:.2f}, o={so:.2f}) -> \"{s}\"")
